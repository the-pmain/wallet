import { spawnSync } from 'node:child_process'
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { resolve } from 'node:path'

import { isLocalSupabaseUrl } from './local-supabase-url.mjs'

const ROOT = resolve('.')
const ENV_LOCAL = resolve(ROOT, '.env.local')
const SUPABASE_KEYS = [
  'SUPABASE_URL',
  'SUPABASE_ANON_KEY',
  'SUPABASE_PUBLISHABLE_KEY',
  'SUPABASE_SERVICE_ROLE_KEY',
]

const status = spawnSync(
  process.execPath,
  [resolve(ROOT, 'node_modules/supabase/dist/supabase.js'), '--agent', 'no', 'status', '-o', 'env'],
  {
    encoding: 'utf8',
    cwd: ROOT,
  },
)

if (status.status !== 0) {
  console.error(
    'Local Supabase is not running or `supabase status` failed. ' +
      'Start it with: npm run local:db',
  )
  process.exit(1)
}

const statusEnv = parseStatus(status.stdout)
const apiUrl = statusEnv['API_URL'] ?? ''
const anonKey = statusEnv['ANON_KEY'] ?? ''
const serviceRoleKey = statusEnv['SERVICE_ROLE_KEY'] ?? ''

if (!isLocalSupabaseUrl(apiUrl)) {
  console.error(
    'Refusing to write .env.local: `supabase status` did not return a local API URL.',
  )
  process.exit(1)
}

if (anonKey === '' || serviceRoleKey === '') {
  console.error('Refusing to write .env.local: `supabase status` did not return local keys.')
  process.exit(1)
}

const nextValues = {
  SUPABASE_URL: apiUrl.replace(/\/$/u, ''),
  SUPABASE_ANON_KEY: anonKey,
  SUPABASE_PUBLISHABLE_KEY: anonKey,
  SUPABASE_SERVICE_ROLE_KEY: serviceRoleKey,
}

const existing = existsSync(ENV_LOCAL) ? readFileSync(ENV_LOCAL, 'utf8') : ''
writeFileSync(ENV_LOCAL, mergeEnvLocal(existing, nextValues), 'utf8')

console.log(
  'Wrote local Supabase keys to .env.local (gitignored). ' +
    `SUPABASE_URL=${nextValues.SUPABASE_URL}`,
)

function parseStatus(raw) {
  const fromEnv = parseEnv(raw)
  if (fromEnv['API_URL']) {
    return fromEnv
  }

  try {
    const parsed = JSON.parse(raw)
    if (parsed && typeof parsed === 'object') {
      return parsed
    }
  } catch {
    /* status printed text, not JSON */
  }

  return fromEnv
}

function parseEnv(raw) {
  const values = {}

  for (const line of raw.split(/\r?\n/u)) {
    const trimmed = line.trim()

    if (trimmed === '' || trimmed.startsWith('#')) {
      continue
    }

    const separator = trimmed.indexOf('=')

    if (separator <= 0) {
      continue
    }

    const key = trimmed.slice(0, separator).trim()
    let value = trimmed.slice(separator + 1).trim()

    if (
      (value.startsWith('"') && value.endsWith('"')) ||
      (value.startsWith("'") && value.endsWith("'"))
    ) {
      value = value.slice(1, -1)
    }

    values[key] = value
  }

  return values
}

function mergeEnvLocal(existing, values) {
  const header =
    '# Generated by `npm run supabase:env` from `supabase status`.\n' +
    '# Local Docker stack only. Do not replace these with Dashboard production keys.\n' +
    '# This file is gitignored. It overrides SUPABASE_* from `.env`.\n'

  const kept = []
  let sawHeader = false

  for (const line of existing.split(/\r?\n/u)) {
    const trimmed = line.trim()

    if (trimmed.startsWith('# Generated by `npm run supabase:env`')) {
      sawHeader = true
      continue
    }

    if (
      sawHeader === false &&
      (trimmed.startsWith('# Local Docker stack only') ||
        trimmed.startsWith('# This file is gitignored'))
    ) {
      continue
    }

    if (trimmed === '' && kept.length === 0) {
      continue
    }

    const separator = trimmed.indexOf('=')
    const key = separator > 0 ? trimmed.slice(0, separator).trim() : ''

    if (SUPABASE_KEYS.includes(key)) {
      continue
    }

    kept.push(line)
  }

  while (kept.length > 0 && kept[0].trim() === '') {
    kept.shift()
  }

  while (kept.length > 0 && kept[kept.length - 1].trim() === '') {
    kept.pop()
  }

  const assigned = SUPABASE_KEYS.map((key) => `${key}=${values[key]}`).join('\n')
  const body = kept.length > 0 ? `${kept.join('\n').trimEnd()}\n\n${assigned}\n` : `${assigned}\n`

  return `${header}\n${body}`
}
